def cluster_of_env(key: str, group: str) -> str:
    """把 env 键归到簇。显式前缀优先于 group（归档/备份/群原文归档各成簇）。"""
    if key in {"SEARCH_ENABLED"}:
        return "search"
    if key in {"AGENT_MUSIC_ENABLED"}:
        return "music"
    if key in {"AGENT_PERSONA_GROWTH_ENABLED"}:
        return "persona"
    if key.startswith("AGENT_GROUP_ARCHIVE"):
        return "group_archive"
    if key.startswith("AGENT_ARCHIVE_") or key.startswith("AGENT_LOG_"):
        return "archive"
    if key.startswith("AGENT_BACKUP_"):
        return "backup"
    if key in {
        "AGENT_HELP_IMAGE",
        "AGENT_DASHBOARD_URL",
        "AGENT_DASHBOARD_TIMEOUT",
        "AGENT_DASHBOARD_TOKEN",
        "AGENT_POKE_ENABLED",
        "AGENT_POKE_COOLDOWN",
    }:
        return "messaging"
    return {
        "模型与推理": "llm",
        "成本预算": "llm",
        "Embedding": "embedding",
        "消息路由": "messaging",
        "图片与媒体": "vision",
        "记忆抽取": "memory",
        "知识库": "kb",
        "搜索": "search",
        "点歌": "music",
        "群统计": "stats",
        "出站投递": "outbound",
        "定时推送": "push",
        "人格": "persona",
    }.get(group, "advanced")


def _validate_llm_model(raw: str) -> str:
    """``LLM_MODEL`` 只接受「模型[@base_url]」——活跃位不携带 key。"""
    from agentcore.llm.client import canonical_spec, parse_model_spec

    try:
        return canonical_spec(parse_model_spec(raw, allow_key=False))
    except ValueError as e:
        raise ValueError(f"bad_model_spec: {e}") from e


