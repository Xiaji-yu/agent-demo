"""全部设置项的单一事实源（ENV_SPECS / YAML_SPECS）。

为什么要有这个文件：同一批键此前在四处各写一遍——`.env.example` 注释、
`config_write.WRITABLE`、设置页前端的 JS 数组、`docs/configuration.md`。
加一个键要改四处，漏一处就是「接口能写、页面没入口」或「页面能点、后端拒绝」
（2026-10-19 实测：`LLM_MODEL` 后端加了、前端漏了）。这里收敛成一份带元数据的
注册表，设置页由 API 返回的 schema 驱动渲染。

字段语义：
- ``writable``：是否允许 web 受控写入。凭据/安全边界/结构路径一律 False，
  它们必须走 SSH——web 只有一个 bearer token，泄漏后不能再升级成「拿走全部凭据」。
- ``secret``：值永不回显（只报「已设置/未设置」）。URL 类也在此列：
  响应体不得含 base_url（AGENTS.md 不变量）。
- ``live``：调用时读取，保存即生效；False = 启动期装配，改后需重启。
  拿不准时一律 False（保守：多提示一次重启，好过谎报已生效）。

本文件**手工维护**（初版由 `.env.example` 引导生成）：新增/删除 env 时同步改
``ENV_SPECS``，`tests/test_web.py::test_schema_covers_env_example_and_invariants`
会核对两边集合完全一致——这是防漂移的主闸，别绕过。
"""

